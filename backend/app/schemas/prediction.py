"""
app/schemas/prediction.py — Request and response schemas for POST /predict.
"""

from pydantic import BaseModel, Field


class PredictionResponse(BaseModel):
    """
    Structured response from POST /predict.

    All probability values sum to 1.0 (±floating point precision).
    The 'confidence' field equals the probability of the top prediction.
    """

    predicted_class: str = Field(
        description="Short class code of the top prediction (e.g. 'mel', 'nv')."
    )
    predicted_class_full_name: str = Field(
        description="Human-readable full name of the predicted class."
    )
    class_index: int = Field(
        description="Integer index of the predicted class (0–6)."
    )
    confidence: float = Field(
        ge=0.0,
        le=1.0,
        description="Softmax probability of the top prediction (0.0–1.0).",
    )
    probabilities: dict[str, float] = Field(
        description=(
            "Softmax probabilities for all 7 classes: "
            "akiec, bcc, bkl, df, mel, nv, vasc."
        )
    )
    disclaimer: str = Field(
        description=(
            "Responsible use notice. This model is for educational/research "
            "purposes only and is NOT a medical diagnostic tool."
        )
    )

    model_config = {"json_schema_extra": {
        "example": {
            "predicted_class": "mel",
            "predicted_class_full_name": "Melanoma",
            "class_index": 4,
            "confidence": 0.7821,
            "probabilities": {
                "akiec": 0.0312,
                "bcc": 0.0241,
                "bkl": 0.0581,
                "df": 0.0093,
                "mel": 0.7821,
                "nv": 0.0841,
                "vasc": 0.0111,
            },
            "disclaimer": (
                "This result is generated by a research AI model for educational "
                "purposes only. It is NOT a medical diagnosis and should NOT be "
                "used as a substitute for professional medical advice. Please "
                "consult a qualified dermatologist for any skin concerns."
            ),
        }
    }}


class ErrorResponse(BaseModel):
    """Standard error response body."""

    error: str = Field(description="Short error category.")
    detail: str = Field(description="Human-readable explanation of what went wrong.")

    model_config = {"json_schema_extra": {
        "example": {
            "error": "invalid_file_type",
            "detail": "Uploaded file type 'text/plain' is not supported. Please upload a JPEG, PNG, WebP, or BMP image.",
        }
    }}
